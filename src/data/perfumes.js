export const formatPrice = (price) => {
  if (price === null || price === undefined) {
    return "Price coming soon";
  }

  return new Intl.NumberFormat("en-NG", {
    style: "currency",
    currency: "NGN",
    maximumFractionDigits: 0,
  }).format(price);
};
